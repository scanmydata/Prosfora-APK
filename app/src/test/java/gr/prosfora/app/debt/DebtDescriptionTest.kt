package gr.prosfora.app.debt

import gr.prosfora.app.data.db.DebtKind
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Οι περιγραφές των οφειλών, πάνω στα **πραγματικά** έντυπα.
 *
 * Τα κείμενα είναι αυτούσια από τα ίδια τα PDF, με τις ιδιοτροπίες τους: το
 * λατινικό `o` μέσα στο «Εισφoρών», τα διπλά κενά, το λατινικό `N` μέσα στο
 * «ΑΡ64N4172/13». Αυτές ακριβώς οι λεπτομέρειες έσπαγαν τα μοτίβα.
 */
class DebtDescriptionTest {

    @Test
    fun `η ΑΠΔ ΙΚΑ λέει ημέρες ασφάλισης, αποδοχές και υποβολή`() {
        val row = DebtParser.parse(APD_IKA, "ΚΑΤΑΘΕΣΗ ΑΠΔ ΙΚΑ ΙΟΥΝΙΟΥ 2026.pdf").single()
        assertEquals(DebtKind.IKA, row.kind)
        assertEquals(1296.83, row.amount, 0.005)
        assertEquals(
            "Εισφορές ΙΚΑ · 112 ημέρες ασφάλισης · αποδοχές 3.741,64 € · υποβολή 70482882",
            row.description,
        )
    }

    @Test
    fun `η ΑΠΔ ΤΕΚΑ ξεχωρίζει από την ΙΚΑ`() {
        val row = DebtParser.parse(APD_TEKA, "ΚΑΤΑΘΕΣΗ ΑΠΔ ΤΕΚΑ ΙΟΥΝΙΟΥ 2026.pdf").single()
        assertEquals(DebtKind.TEKA, row.kind)
        assertEquals(18.72, row.amount, 0.005)
        assertEquals(
            "Εισφορές ΤΕΚΑ · 12 ημέρες ασφάλισης · αποδοχές 312,05 € · υποβολή 70482997",
            row.description,
        )
    }

    @Test
    fun `τα διαφημιστικά τέλη λένε ποσοστό, κόστος και υποβολή`() {
        val row = DebtParser.parse(EDOEAP, "Report.pdf").single()
        assertEquals(DebtKind.ADVERTISING, row.kind)
        assertEquals(4.26, row.amount, 0.005)
        assertEquals(
            "Εισφορές διαφήμισης ΕΔΟΕΑΠ 2% · κόστος διαφήμισης 212,77 € · υποβολή 20654651",
            row.description,
        )
    }

    /**
     * Το είδος φόρου τυπώνεται κάτω από την ετικέτα του μόνο όταν το OCR
     * κρατήσει τη σειρά. Εδώ την κρατάει.
     */
    @Test
    fun `η ΑΑΔΕ γράφει το είδος φόρου με την τιμή δίπλα στην ετικέτα`() {
        val row = DebtParser.parse(AADE_INTERLEAVED, "Τ.Ο ΟΦΕΙΛΗΣ ΕΛ ΕΠΑΓ.pdf").single()
        assertEquals("ΑΜΟΙΒΕΣ ΑΠΟ ΕΠΙΧΕΙΡ.ΔΡΑΣΤΗΡ.ΑΡ64Ν4172/13", row.description)
    }

    /** Και όταν το OCR βγάλει το έντυπο σε στήλες, που ήταν και το σπάσιμο. */
    @Test
    fun `η ΑΑΔΕ γράφει το είδος φόρου και σε διάταξη στηλών`() {
        val row = DebtParser.parse(AADE_COLUMNAR, "Τ.Ο ΟΦΕΙΛΗΣ ΦΜΥ.pdf").single()
        assertEquals("ΠΡΟΣΩΡ.ΦΟΡΟΥ ΜΙΣΘΩΤΩΝ ΥΠΗΡΕΣ.Ν.4172/2013", row.description)
    }

    /** Χωρίς παραπομπή νόμου δεν μαντεύουμε: μένει η γενική περιγραφή. */
    @Test
    fun `χωρίς είδος φόρου μένει η γενική περιγραφή`() {
        val text = AADE_COLUMNAR
            .replace("ΠΡΟΣΩΡ.ΦΟΡΟΥ ΜΙΣΘΩΤΩΝ\nΥΠΗΡΕΣ.Ν.4172/2013\n", "")
        assertEquals(
            "Βεβαιωμένη οφειλή εκτός ρύθμισης",
            DebtParser.parse(text, "Τ.Ο.pdf").single().description,
        )
    }

