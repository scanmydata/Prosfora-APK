package gr.prosfora.app.data.db

/**
 * Οι ταφόπλακες των οριστικά διαγραμμένων εργαζομένων.
 *
 * Όταν διαγράφεις έναν εργαζόμενο «και από τη βάση», το id του μπαίνει σε ένα
 * τοπικό σύνολο ώστε να μην τον ξαναφέρει ο επόμενος συγχρονισμός από το φύλλο.
 * Χρήσιμο — αλλά η ταφόπλακα ήταν **παντοτινή**: έφευγε μόνο αν άνοιγες την
 * καρτέλα και την αποθήκευες με το χέρι, δηλαδή ακριβώς όταν του έδινες
 * ψευδώνυμο. Γι' αυτό στο φύλλο έφταναν μόνο όσοι είχαν ψευδώνυμο.
 *
 * Μια νέα, μη διαγραμμένη μισθοδοσία είναι απόδειξη ότι ο άνθρωπος δουλεύει
 * ξανά. Η απόδειξη υπερισχύει μιας τοπικής προτίμησης: η ταφόπλακα σηκώνεται.
 */
object EmployeeTombstones {

    /**
     * Ποιες ταφόπλακες πρέπει να σηκωθούν, δεδομένων των καρτελών που μόλις
     * ξαναχτίστηκαν από **ζωντανές** μισθοδοσίες.
     *
     * Κοιτάζονται και το id και ο ΑΜ ΙΚΑ: η διαγραφή αποθηκεύει όποιο από τα
     * δύο ήξερε τη στιγμή εκείνη, και τα δύο μπλοκάρουν τον ίδιο άνθρωπο.
     */
    fun revived(tombstones: Set<String>, live: Collection<EmployeeEntity>): Set<String> {
        if (tombstones.isEmpty() || live.isEmpty()) return emptySet()
        val names = live.flatMapTo(mutableSetOf()) { employee ->
            listOf(employee.id.trim(), EmployeeEntity.normalizeIka(employee.amIka))
        }
        names.remove("")
        return tombstones.filterTo(mutableSetOf()) { it.trim() in names }
    }
}
